// Niveau long en U autour de la chambre de la balise : son signal sert de boussole (toujours « vers
// l'intérieur »). On économise la vue : mémoire, balise et courants plutôt que des impulsions.
// 1. Salle de recharge (NO) : pilier en losange, antichambre, niche en L à perle. Aucun danger :
//    on vide la jauge et on sent la recharge lente.
// 2. Le canal : courant porteur de 2 cases (on avance sans émettre), remous à perle au nord, oursin
//    dans le second coude (qui fonce à l'aveugle s'y pique). Bassin calme : point de contrôle 1.
// 3. Caverne du premier Guetteur : on la traverse (piliers SO et NE, dent sud) jusqu'au levier a du
//    recoin NE, point d'émission sûr ; la porte A s'ouvre au sud, à 11,5 cases de son apparition.
//    Perle dans l'alcôve nord (risque). La colonne est (courant) descend sans effort vers le point
//    de contrôle 2, remous à perle en chemin.
// 4. Le marais : entrée au SE (émission sûre, même longue), gué de vase sur l'anneau sud (lent,
//    aveugle, étouffe le son), puis fin de l'anneau à portée d'écoute du deuxième Guetteur, tapi au
//    coin NO. Perle dans son alcôve. L'anneau nord, par chez lui, est un détour plus risqué.
// 5. Carrefour (point de contrôle 3) : slalom d'oursins de 3 cases (une impulsion longue depuis le
//    carrefour le dévoile), antre du troisième Guetteur (perle au coin NO), levier b au coin SO, que
//    l'on trouve en longeant la paroi sud ; retour par le courant. La porte B ouvre la chambre de la
//    balise, calme, derrière un pilier.
