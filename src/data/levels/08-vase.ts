// 1. Alcôve de départ, puis salle calme autour d'une mare de vase : l'anneau s'y éteint et laisse
//    un trou dans la carte. La sortie est dans l'ombre de la mare (contourner ou traverser
//    lentement). Perle dans une niche au sud, pilier-repère au sud-est.
// 2. Salle barrée d'un champ de vase d'une paroi à l'autre (7 à 9 cases) : on devine son contour à
//    l'absence d'écho. Choix : traverser à l'aveugle, lent mais économe, ou le détour nord, plus
//    rapide mais à cartographier (courant porteur, deux oursins en quinconce, perle en poche).
//    Point de contrôle P1 dans la niche qui suit.
// 3. Le gué : rive nord abritée (capsule), 8 cases de vase vers la rive sud, antre du Guetteur 1
