//    rives, mais une impulsion lâchée dans le gué ou une dérive vers l'antre le réveille, et la
//    fuite dans la vase est lente. Variante en eau libre par l'antre (perle) via le passage nord.
//    Point de contrôle P2 au sortir de la rive sud.
// 4. Bassin du Guetteur 2 : au nord, son territoire (perle en baie, risque) ; au milieu, une
//    vasière ; au sud, caché derrière elle, un couloir de courant porteur semé d'oursins, abrité
//    du Guetteur par la vase (perle dans un remous). Entrée abritée avec capsule, puis chambre
//    calme de la balise à l'est.
